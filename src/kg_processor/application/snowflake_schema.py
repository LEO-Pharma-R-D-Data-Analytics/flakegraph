def split_sql_statements(sql: str) -> list[str]:
    """Split rendered SQL into executable statements."""

    return [statement.strip() for statement in sql.split(";") if statement.strip()]


def snowflake_schema_columns() -> dict[str, tuple[str, ...]]:
    """Return the table/column contract that the rendered setup SQL creates.

    The access checker uses this helper before a production run to verify that
    the active role can see the schema shape the worker expects. Deriving the
    contract from rendered DDL keeps setup SQL, readiness checks, and tests from
    quietly drifting apart as tables evolve.
    """

    columns_by_table: dict[str, tuple[str, ...]] = {}
    sql = render_snowflake_schema_sql(_SCHEMA_INTROSPECTION_DIMENSION)
    for statement in split_sql_statements(sql):
        match = _CREATE_TABLE_RE.fullmatch(statement)
        if not match:
            continue
        table_name = match.group("table")
        columns = tuple(
            column_match.group("column")
            for line in match.group("body").splitlines()
            if (column_match := _COLUMN_DEFINITION_RE.match(line.strip().rstrip(",")))
        )
        columns_by_table[table_name] = columns
    return columns_by_table


def _validate_dimension(value: int) -> int:
    if value <= 0 or value > _MAX_VECTOR_DIMENSION:
        raise ValueError("Snowflake VECTOR dimension must be between 1 and 4096")
    return value


_MAX_VECTOR_DIMENSION = 4096
