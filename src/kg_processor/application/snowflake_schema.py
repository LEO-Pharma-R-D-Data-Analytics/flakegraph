"""Snowflake logical table DDL for the canonical graph artifact contract."""

from __future__ import annotations

import re

_SCHEMA_INTROSPECTION_DIMENSION = 1536
_CREATE_TABLE_RE = re.compile(
    r"CREATE TABLE IF NOT EXISTS\s+(?P<table>[A-Z][A-Z0-9_]*)\s*\((?P<body>.*)\)\s*\Z",
    re.DOTALL,
)
_COLUMN_DEFINITION_RE = re.compile(r"^\s*(?P<column>[A-Z][A-Z0-9_]*)\s+")


